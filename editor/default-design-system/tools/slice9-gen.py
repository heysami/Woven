#!/usr/bin/env python3
# slice9-gen.py - procedural slice-9 frame generator (proof / reference).
# ============================================================================
# Generates a border-image atlas PER SKIN to a KNOWN GEOMETRY, so the four
# slice insets are exact BY CONSTRUCTION (no detection needed). Each frame is
# drawn at 1 art-pixel == 1 source-pixel; the CSS upscales it with
# image-rendering:pixelated, so corners stay crisp at any element size.
#
# This is the cheap, deterministic path for GEOMETRIC game-UI skins. Ornate
# skins (gold filigree, carved stone) take the image-gen path instead: the same
# geometry contract, generated by a model, then normalised by tools/slice9_detect.py.
#
#   python3 slice9-gen.py            # writes ../assets/slice9/<skin>/*.png + atlas.json
#                                    # + ../assets/slice9/_gallery.html (all skins)
#
# Adding a skin = one entry in SKINS. Each skin owns its tile/corner/scale and a
# role->painter map. Painters are built from a generic ring model:
#   make_frame(layers, body, chamfer, pressed)
#     layers: [(thickness, spec), ...] outside-in; spec = rgba | ("bevel", hi, sh)
#     body:   rgba | ("grad", topRGBA, botRGBA) | callable(x,y,w,h)
#     chamfer: NES-style diagonal corner cut (px), 0 = square
# ============================================================================
import json, os

from PIL import Image

OUT_ROOT = os.path.join(os.path.dirname(__file__), "..", "assets", "slice9")
CLEAR = (0, 0, 0, 0)


def hx(s, a=255):
    s = s.lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16), a)


def lerp(c0, c1, t):
    return tuple(round(c0[i] + (c1[i] - c0[i]) * t) for i in range(4))


def edge_dist(x, y, w, h):
    return min(x, y, w - 1 - x, h - 1 - y)


def make_frame(layers, body, chamfer=1, pressed=False):
    """Return a px(x,y,w,h)->rgba painter from an outside-in ring spec."""
    def bodycol(x, y, w, h):
        if callable(body):
            return body(x, y, w, h)
        if isinstance(body, tuple) and len(body) == 3 and body[0] == "grad":
            _, top, bot = body
            t = y / (h - 1) if h > 1 else 0
            return lerp(top, bot, t)
        return body

    def px(x, y, w, h):
        # diagonal corner cut (rounded pixel corner)
        if chamfer > 0:
            cx = min(x, w - 1 - x)
            cy = min(y, h - 1 - y)
            if cx + cy < chamfer:
                return CLEAR
        depth = edge_dist(x, y, w, h)
        acc = 0
        for th, spec in layers:
            if depth < acc + th:
                if isinstance(spec, tuple) and spec and spec[0] == "bevel":
                    _, hi, sh = spec
                    top_left = (x + y) < (w - 1)
                    if pressed:
                        return sh if top_left else hi
                    return hi if top_left else sh
                return spec
            acc += th
        return bodycol(x, y, w, h)

    return px


# ----------------------------------------------------------------------------
# SKINS - each maps a library aesthetic to a role->painter set.
# ----------------------------------------------------------------------------
def skin_8bit():
    INK = hx("#1a1c2c"); WHITE = hx("#f4f4f4")
    PANEL = hx("#29366f"); CARD = hx("#3a4a8c")
    FACE = hx("#5b6ee1"); HI = hx("#9aaaff"); SH = hx("#2d3478"); DOWN = hx("#46568c")
    FIELD = hx("#f4f4f4"); FHI = hx("#ffffff"); FSH = hx("#96a0c8")
    return dict(
        id="8bit", label="8-bit generic", library="aesthetic-8-bit-generic",
        tile=24, corner=8, scale=3,
        roles=dict(
            panel=make_frame([(1, INK), (1, WHITE)], PANEL),
            card=make_frame([(1, INK), (1, WHITE)], CARD),
            button=make_frame([(1, INK), (1, ("bevel", HI, SH))], FACE),
            **{"button-active": make_frame([(1, INK), (1, ("bevel", HI, SH))], DOWN, pressed=True)},
            input=make_frame([(1, INK), (1, ("bevel", FHI, FSH))], FIELD, pressed=True),
        ),
    )


