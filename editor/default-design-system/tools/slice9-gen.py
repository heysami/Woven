SKINS = [skin_8bit(), skin_snes(), skin_scifi(), skin_cozy()]


def render(fn, tile):
    img = Image.new("RGBA", (tile, tile), CLEAR)
    px = img.load()
    for y in range(tile):
        for x in range(tile):
            px[x, y] = fn(x, y, tile, tile)
    return img


def build_skin(skin):
    out = os.path.join(OUT_ROOT, skin["id"])
    os.makedirs(out, exist_ok=True)
    tile, corner, scale = skin["tile"], skin["corner"], skin["scale"]
    frames = {}
    for role, fn in skin["roles"].items():
        render(fn, tile).save(os.path.join(out, role + ".png"))
        ctl = role in ("button", "button-active", "input")
        frames[role] = {
            "src": role + ".png",
            "slice": [corner, corner, corner, corner],   # t r b l (source px)
            "fill": True,
            "width": corner * (scale - 1 if ctl else scale),  # controls thinner than panels
            "repeat": "stretch",
            "role": role,
        }
    manifest = {
        "id": skin["id"], "label": skin["label"], "library": skin["library"],
        "tile": tile, "corner": corner, "imageRendering": "pixelated", "frames": frames,
    }
    with open(os.path.join(out, "atlas.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    return manifest


def write_gallery(manifests):
    """Self-maintaining proof page: every skin x role, driven by the manifest
    values (proving the manifest is the single source the render obeys)."""
    secs = []
    for m in manifests:
        cells = []
        for role, fr in m["frames"].items():
            sl = " ".join(str(v) for v in fr["slice"]) + (" fill" if fr.get("fill") else "")
            tag = "button" if "button" in role else ("input" if role == "input" else "div")
            label = {"panel": "Panel", "card": "Card", "button": "Button",
                     "button-active": "Pressed", "input": "Input"}.get(role, role)
            # NB: url() in a custom property resolves relative to the STYLESHEET
            # that consumes it (components/slice9.css), not this document - so the
            # path must be written relative to components/, not to _gallery.html.
            style = (
                "--s9-src:url('../assets/slice9/%s/%s');--s9-slice:%s;--s9-width:%dpx;"
                % (m["id"], fr["src"], sl, fr["width"])
            )
            inner = "" if tag == "div" else ("placeholder='search'" if tag == "input" else "")
            box = ("width:150px;height:90px" if role in ("panel", "card") else "min-width:120px")
            content = "" if tag == "input" else label
            if tag == "input":
                cells.append("<input class='s9' style=\"%s%s\" %s>" % (style, box, inner))
            else:
                cells.append("<%s class='s9' style=\"%s%s\">%s</%s>" % (tag, style, box, content, tag))
        secs.append(
            "<section><h2>%s <small>%s &middot; %d&times;%d tile, %dpx corner</small></h2>"
            "<div class='row'>%s</div></section>"
            % (m["label"], m["library"], m["tile"], m["tile"], m["corner"], "".join(cells))
        )
    html = """<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Slice-9 atlas gallery</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400;600;700&display=swap">
<link rel="stylesheet" href="../../components/slice9.css">
<style>
 body{margin:0;background:#11131f;color:#e8eaf2;font-family:'Plus Jakarta Sans',system-ui,sans-serif;padding:28px 32px 80px}
 h1{font-size:22px;margin:0 0 4px} .lede{color:#9aa0c0;margin:0 0 26px;font-size:14px}
 section{margin:0 0 30px} h2{font-size:16px;margin:0 0 12px;letter-spacing:.02em}
 h2 small{color:#8b90b4;font-weight:400;font-size:12px;margin-left:8px}
 .row{display:flex;gap:18px;align-items:center;flex-wrap:wrap}
 .s9{color:#fff;display:inline-flex;align-items:center;justify-content:center;font-weight:600;font-size:14px}
 input.s9{color:#1a1c2c}
</style></head><body>
<h1>Slice-9 game-UI atlases</h1>
<p class="lede">Every skin &times; role, each cell driven by its <code>atlas.json</code> slice/width values via <code>border-image</code>. One raster per frame.</p>
%s
</body></html>""" % "\n".join(secs)
    with open(os.path.join(OUT_ROOT, "_gallery.html"), "w") as f:
        f.write(html)


def main():
    os.makedirs(OUT_ROOT, exist_ok=True)
    manifests = [build_skin(s) for s in SKINS]
    write_gallery(manifests)
    print("built %d skins:" % len(manifests), ", ".join(m["id"] for m in manifests))
    print("gallery:", os.path.normpath(os.path.join(OUT_ROOT, "_gallery.html")))


if __name__ == "__main__":
    main()
