# ── main ─────────────────────────────────────────────────────────────────────
def build(ds_dir, strict=False):
    """Returns (ds, wrote: bool). ds is None when not a component DS."""
    ds = ds_model.load(ds_dir)
    if ds.kind != "component":
        return None, False
    errors = [f for f in ds.findings if f.level == "error"]
    if strict and errors:
        return ds, False
    build_dir = os.path.join(ds.dir, "build")
    version = ds.version()
    man = manifest(ds, version)
    _write(os.path.join(build_dir, "ds.css"), build_css(ds, build_dir))
    _write(os.path.join(build_dir, "ds-runtime.js"), build_runtime(ds, man))
    _write(os.path.join(build_dir, "manifest.json"), json.dumps(man, indent=1, ensure_ascii=False) + "\n")
    _write(os.path.join(build_dir, "CATALOG.md"), build_catalog(ds, man, "../../design-systems/" + ds.id))
    gallery = build_gallery(ds, man)
    _write(os.path.join(build_dir, "gallery.html"), gallery)
    # The editor's DS surfaces (DS node, library viewer, global DS sync) open
    # <ds>/gallery.html. Mirror the generated gallery there, but never over a
    # hand-written one (a DS mid-conversion still has its legacy gallery).
    root_gallery = os.path.join(ds.dir, "gallery.html")
    if not os.path.exists(root_gallery) or GENERATED_MARK in _read(root_gallery)[:4000]:
        _write(root_gallery, gallery.replace('href="ds.css"', 'href="build/ds.css"').replace('src="ds-runtime.js"', 'src="build/ds-runtime.js"'))
    return ds, True


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate a component design system's build/ folder")
    ap.add_argument("--ds-dir", required=True)
    ap.add_argument("--strict", action="store_true", help="refuse to write build/ when the DS has errors")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)
    ds, wrote = build(a.ds_dir, a.strict)
    if ds is None:
        print("build_ds: " + a.ds_dir + " is not a component design system (meta.json kind)")
        return 2
    counts = {"error": 0, "warn": 0, "info": 0}
    for f in ds.findings:
        counts[f.level] = counts.get(f.level, 0) + 1
    if not a.quiet:
        for f in sorted(ds.findings, key=lambda f: ({"error": 0, "warn": 1}.get(f.level, 2), f.file or "", f.line or 0)):
            print(f.fmt(os.getcwd()))
    print("build_ds " + ds.id + ": " + ("wrote build/ (" + str(len(ds.blocks)) + " blocks)" if wrote else "NOT written (--strict)")
          + ", " + str(counts["error"]) + " errors, " + str(counts["warn"]) + " warnings")
    return 1 if counts["error"] else 0


