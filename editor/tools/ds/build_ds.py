def _e(s):
    return htmllib.escape(str(s), quote=True)


def _source_tag(name, props, slots):
    attrs = ""
    for k, v in (props or {}).items():
        if v is True:
            attrs += " " + k
        elif isinstance(v, (list, tuple)):
            attrs += " " + k + '="' + ",".join(str(x) for x in v) + '"'
        elif isinstance(v, (dict,)):
            attrs += " " + k + "='" + json.dumps(v) + "'"
        else:
            attrs += " " + k + '="' + str(v) + '"'
    inner = " ".join(("[" + k + "] " if k != "default" else "") + re.sub(r"\s+", " ", v).strip() for k, v in (slots or {}).items())
    return "<ds-" + name + attrs + ">" + inner + "</ds-" + name + ">"


