#!/usr/bin/env python3
"""build_ds.py - generate a component design system's build/ folder.

    python3 build_ds.py --ds-dir <project>/design-systems/<id> [--strict] [--quiet]

Writes build/ds.css, build/ds-runtime.js, build/manifest.json, build/CATALOG.md
and build/gallery.html from the DS sources. Never hand-edit build/.
Spec: docs/features/component-ds-format.md. Stdlib only, Python 3.9-safe.

Exit codes: 0 built clean, 1 built with errors (or refused with --strict),
2 not a component design system.
"""

import argparse
import html as htmllib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ds_model  # noqa: E402

RUNTIME_SRC = os.path.join(HERE, "runtime", "ds-runtime.src.js")
GENERATED_MARK = "GENERATED by editor/tools/ds/build_ds.py"
LAYER_TITLES = [("layout", "Layout"), ("atom", "Atoms"), ("molecule", "Molecules"), ("organism", "Organisms"),
                ("pattern", "Patterns"), ("shell", "Shells")]
URL_RE = re.compile(r"url\(\s*(['\"]?)([^'\")]+)\1\s*\)")
IMPORT_RE = re.compile(r"@import\s+(?:url\()?\s*['\"]?(https?:[^'\")\s]+|//[^'\")\s]+)['\"]?\s*\)?[^;]*;")


def _read(p):
    with open(p, "r", encoding="utf-8", errors="replace") as f:
        return f.read()


def _write(p, text):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    tmp = p + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, p)


def _js_json(obj):
    """JSON safe to drop into a script (no closing script tag sequence)."""
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


# ── CSS bundle ───────────────────────────────────────────────────────────────
def _rewrite_urls(css, src_dir, build_dir):
    def sub(m):
        q, u = m.group(1), m.group(2).strip()
        if re.match(r"^([a-z]+:|//|#|/|var\()", u):
            return m.group(0)
        path, _, rest = u.partition("?")
        path, _, frag = path.partition("#")
        rel = os.path.relpath(os.path.normpath(os.path.join(src_dir, path)), build_dir).replace(os.sep, "/")
        if rest:
            rel += "?" + rest
        if frag:
            rel += "#" + frag
        return "url(" + q + rel + q + ")"
    return URL_RE.sub(sub, css)


def block_order(ds):
    """Every block with a style.css, in CSS order: by layer rank (layout, atom,
    molecule, organism, pattern, shell), then name, with each block's
    `contains` emitted BEFORE it so a parent's context rules win ties."""
    rank = dict((l, i) for i, l in enumerate(ds_model.LAYER_RANK))
    names = sorted(ds.blocks, key=lambda n: (rank.get(ds.blocks[n].spec.get("layer"), 99), n))
    out, seen = [], set()

    def visit(n, trail):
        if n in seen or n in trail or n not in ds.blocks:
            return
        b = ds.blocks[n]
        for c in sorted(b.spec.get("contains", []) or [], key=lambda c: (rank.get(ds.blocks[c].spec.get("layer"), 99), c) if c in ds.blocks else (99, c)):
            visit(c, trail | {n})
        seen.add(n)
        if b.style:
            out.append(n)
    for n in names:
        visit(n, set())
    return out


def build_css(ds, build_dir):
    """ONE plain stylesheet (no @layer): tokens, foundations, blocks, themes.
    Specificity and source order behave exactly like a hand-written single
    stylesheet, which is what a converted DS was verified against."""
    imports = []

    def take(path):
        css = _read(path)
        for m in IMPORT_RE.finditer(css):
            if m.group(0) not in imports:
                imports.append(m.group(0))
        css = IMPORT_RE.sub("", css)
        css = _rewrite_urls(css, os.path.dirname(path), build_dir)
        rel = os.path.relpath(path, ds.dir).replace(os.sep, "/")
        return "/* " + rel + " */\n" + css.strip() + "\n"

    groups = [("tokens", [p for k, p in ds.css_files if k == "tokens"]),
              ("foundations", [p for k, p in ds.css_files if k == "base"]),
              ("blocks", [ds.blocks[n].style for n in block_order(ds)]),
              ("themes", [p for k, p in ds.css_files if k == "themes"])]
    sections = []
    for title, files in groups:
        if files:
            sections.append("/* ==== " + title + " ==== */\n" + "\n".join(take(p) for p in files))
    head = ("/* GENERATED by editor/tools/ds/build_ds.py from design-systems/" + ds.id + "/ - do not edit.\n"
            "   Order: tokens, foundations, blocks (contained blocks first), themes. Pages never select a DS class. */\n")
    return head + "".join(i + "\n" for i in imports) + "\n" + "\n".join(sections)


# ── runtime ──────────────────────────────────────────────────────────────────
def manifest(ds, version):
    blocks = {}
    for name in sorted(ds.blocks):
        b = ds.blocks[name]
        s = b.spec
        blocks[name] = {
            "name": name, "title": s.get("title") or name, "layer": s.get("layer"), "kind": b.kind,
            "oneLine": s.get("oneLine", ""), "useWhen": s.get("useWhen", ""), "notForUseWhen": s.get("notForUseWhen", ""),
            "props": s.get("props", {}) or {}, "slots": s.get("slots"), "rootClass": b.root_class,
            "replaces": s.get("replaces", []) or [], "contains": s.get("contains", []) or [],
            "events": s.get("events", []) or [], "states": s.get("states", []) or [],
            "copy": s.get("copy", {}) or {}, "template": b.template.strip(),
            "examples": b.examples,
        }
    return {
        "id": ds.id, "label": ds.meta.get("label") or ds.id, "version": version, "format": ds_model.FORMAT,
        "blocks": blocks, "icons": ds.icons,
        "defaultIconStyle": ds.meta.get("defaultIconStyle") or ("filled" if "filled" in ds.icons else (sorted(ds.icons)[0] if ds.icons else "filled")),
        "services": [{"name": n, "desc": d} for n, d, _ in ds.services],
    }


def build_runtime(ds, man):
    parts = ["/* GENERATED by editor/tools/ds/build_ds.py from design-systems/" + ds.id + "/ (version " + man["version"] + ") - do not edit. */\n",
             _read(RUNTIME_SRC), "\n"]
    payload = dict(man)
    payload["blocks"] = dict((n, dict((k, v) for k, v in b.items() if k != "examples")) for n, b in man["blocks"].items())
    parts.append("DS.__load(" + _js_json(payload) + ");\n")
    for name, desc, path in ds.services:
        parts.append("\n/* services/" + os.path.basename(path) + " */\n;(function (DS) {\n" + _read(path).rstrip() + "\n})(window.DS);\n")
    for name in sorted(ds.blocks):
        b = ds.blocks[name]
        if b.behavior:
            rel = os.path.relpath(b.behavior, ds.dir).replace(os.sep, "/")
            parts.append("\n/* " + rel + " */\n;(function (DS) {\n" + _read(b.behavior).rstrip() + "\n})(window.DS);\n")
    parts.append("\nDS.__boot();\n")
    return "".join(parts)


# ── catalog ──────────────────────────────────────────────────────────────────
def _sig(b):
    bits = []
    for pn, ps in (b["props"] or {}).items():
        t = ps.get("type", "string")
        s = pn + ("!" if ps.get("required") else "")
        if t == "enum":
            s += ":" + "|".join(str(v) for v in ps.get("values", []))
            if "default" in ps:
                s += "=" + str(ps["default"])
        elif t != "string":
            s += ":" + ("bool" if t == "boolean" else t)
            if "default" in ps:
                s += "=" + json.dumps(ps["default"])
        bits.append(s)
    out = "<ds-" + b["name"] + (" " + " ".join(bits) if bits else "") + ">"
    slots = b.get("slots")
    if slots:
        sl = []
        for sn, sp in slots.items():
            acc = sp.get("accepts", "any") if isinstance(sp, dict) else "any"
            sl.append(sn + "(" + ("|".join(acc) if isinstance(acc, list) else acc) + ")")
        out += " slots: " + ", ".join(sl)
    return out


def build_catalog(ds, man, ds_rel_hint):
    L = []
    L.append("# " + man["label"] + " - block catalog")
    L.append("")
    L.append("GENERATED from design-systems/" + ds.id + "/ (version " + man["version"] + "). Do not edit; edit the block folders and rebuild.")
    L.append("")
    L.append("Pages are built ONLY by placing these blocks. Rules:")
    L.append("1. Static markup: `<ds-name prop=\"value\">`. JS: `DS.html(\"name\", {props}, {slot: html})` returns final markup; never hand-write a block's classes.")
    L.append("2. Raw HTML only inside `<ds-custom reason=\"why no block fits\">`. Never style a DS class from a page; no inline styles on blocks.")
    L.append("3. In `<head>`: `<link rel=\"stylesheet\" href=\"" + ds_rel_hint + "/build/ds.css\">` and `<script src=\"" + ds_rel_hint + "/build/ds-runtime.js\"></script>`.")
    L.append("4. Passthrough attributes on any block: id, class (placement only), data-*, aria-*, hidden, title, role, tabindex. `slot=\"name\"` puts a child in a named slot.")
    L.append("5. Blocks talk through attributes and `ds:*` events; page JS listens with addEventListener. Persistent state (which tab is active) is a prop, never a class.")
    L.append("")
    L.append("Signature: `prop!` required, `prop:a|b=a` enum with default, `:bool` `:number` `:list` (comma-separated) `:json`. `slots: name(accepts)`.")
    for layer, title in LAYER_TITLES:
        rows = [b for b in man["blocks"].values() if b["layer"] == layer]
        if not rows:
            continue
        L.append("")
        L.append("## " + title)
        for b in sorted(rows, key=lambda x: x["name"]):
            line = _sig(b) + "  " + b["oneLine"].rstrip(".") + "."
            if b.get("useWhen"):
                line += " Use: " + b["useWhen"].rstrip(".") + "."
            if b.get("notForUseWhen"):
                line += " Not for: " + b["notForUseWhen"].rstrip(".") + "."
            if b.get("replaces"):
                line += " Replaces " + ", ".join("<" + r + ">" for r in b["replaces"]) + "."
            if b.get("events"):
                line += " Emits " + ", ".join(b["events"]) + "."
            L.append("- " + line)
    if man["services"]:
        L.append("")
        L.append("## Services (shared functions)")
        for s in man["services"]:
            L.append("- `DS." + s["name"] + "` " + (s["desc"] or ""))
    L.append("")
    L.append("## Runtime")
    L.append("- `DS.html(name, props, slots)` expanded markup string; `DS.expand(el)` expand <ds-*> tags inserted by hand; `DS.update(root, props)` re-render one block; `DS.props(root)`; `DS.emit(el, type, detail)`; `DS.icon(name, {style})`; `DS.ready(fn)`.")
    if man["icons"]:
        L.append("")
        styles = sorted(man["icons"])
        names = sorted(set(n for s in styles for n in man["icons"][s]))
        L.append("## Icons (" + str(len(names)) + "; styles: " + ", ".join(styles) + "; default " + man["defaultIconStyle"] + ")")
        if len(names) <= 600:
            L.append(", ".join(names))
        else:
            L.append("Too many to list; see build/manifest.json `icons`.")
    return "\n".join(L) + "\n"


